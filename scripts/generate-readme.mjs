const website = 'https://rcl-robotics.github.io/Awesome-World-Action-Models/';
const library = `${website}papers/`;
const generatedNotice = '<!-- Generated by scripts/generate-readme.mjs. Update the source data or generator, then regenerate. -->';
const escape = (value) => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\|/g, '&#124;').replace(/\[/g, '&#91;').replace(/\]/g, '&#93;').replace(/[\r\n]+/g, ' ');
const link = (label, url) => `[${escape(label)}](<${url.replace(/>/g, '%3E').replace(/</g, '%3C')}>)`;
const majorAnchor = (category) => category === null ? 'major-not-recorded' : category === 'WAM' ? 'major-wam' : category === 'WAM Components' ? 'major-wam-components' : `major-${taxonomyLabel(category).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`;
const majorLabel = (category) => category === null ? 'Major category not recorded' : taxonomyLabel(category);
const browse = (key, value) => `${library}?${key}=${encodeURIComponent(value ?? '__unassigned__')}#library`;
const quadrantLabel = (quadrant) => {
  const index = QUADRANTS.indexOf(quadrant);
  return index >= 0 ? `Q${index + 1}` : quadrant === null ? 'Quadrant not recorded' : taxonomyLabel(quadrant);
};
const categoryDescriptions = {
  'Foundational work': 'World models, model-based RL, planning, theory, and surveys',
  VLA: 'Vision-language-action policies and their learning methods',
  WAMs: 'Models connecting world prediction with action generation and control',
  Datasets: 'Robot demonstrations, interaction data, video, and multimodal resources',
  'Evaluation metrics': 'Prediction quality, action consistency, and control performance',
  'Benchmarks & simulators': 'Evaluation tasks, environments, and simulation platforms',
  'Components of WAMs': 'Encoders, predictive backbones, action interfaces, and training methods',
};

function catalog(inputPapers, inputMeta) {
  const papers = sortPapers(validatePapers(inputPapers));
  const meta = validateMeta(inputMeta, papers);
  const majorGroups = [...MAJOR_CATEGORIES, ...(papers.some(paper => paper.majorCategory === null) ? [null] : [])];
  return { papers, meta, majorGroups, stats: coverage(papers) };
}

