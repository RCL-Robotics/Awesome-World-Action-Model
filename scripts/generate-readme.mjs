export function renderPaperCatalog(inputPapers, inputMeta) {
  const { papers, meta, majorGroups, stats } = catalog(inputPapers, inputMeta);
  const lines = [
    generatedNotice, '# Paper catalog', '',
    `[← Repository overview](../README.md) · [Search the collection](${library}#library) · [Reading reports](${website}reports/)`, '',
    `**${stats.papers} entries** · Catalog updated ${meta.updatedAt.slice(0, 10)}`, '',
    'Each entry appears once below, under its recorded major category. Subcategories and quadrants describe different aspects of a contribution. Original research topics are retained as a separate thematic index.', '',
    '## Category index', '',
    '| Category | Entries |', '| --- | ---: |',
    ...majorGroups.map(category => `| [${escape(majorLabel(category))}](#${majorAnchor(category)}) | ${papers.filter(paper => paper.majorCategory === category).length} |`), '',
    '[Classification summary](#classification-summary) · [Research topics](#research-topics)', '',
  ];
  for (const category of majorGroups) {
    lines.push(`<a id="${majorAnchor(category)}"></a>`, '', `## ${majorLabel(category)}`, '', '[↑ Category index](#category-index)', '', '| Date / year | Paper or reference | Links | Subcategories · quadrant |', '| --- | --- | --- | --- |');
    for (const paper of papers.filter(entry => entry.majorCategory === category)) {
      const links = [link(paper.arxivUrl ? 'arXiv' : 'Paper', paper.paperUrl), ...paper.codeUrls.map((url, index) => link(paper.codeUrls.length > 1 ? `Code ${index + 1}` : 'Code', url))];
      if (paper.pdfUrl && paper.pdfUrl !== paper.paperUrl) links.push(link('PDF', paper.pdfUrl));
      if (paper.doi && paper.doi !== paper.paperUrl) links.push(link('DOI', paper.doi));
      if (paper.projectUrl) links.push(link('Project', paper.projectUrl));
      if (paper.venue) links.push(escape(venueLabel(paper.venue)));
      const classification = [...paper.subcategories.map(name => escape(taxonomyLabel(name))), escape(quadrantLabel(paper.quadrant))];
      lines.push(`| ${paper.submittedDate ?? paper.publicationYear ?? '—'} | ${escape(paper.title)} | ${links.join(' · ')} | ${classification.join(' · ')} |`);
    }
    lines.push('');
  }
  lines.push(
    '## Classification summary', '',
    'Quadrants cross architecture and prediction paradigm. The remaining states stay separate; missing classifications are not inferred.', '',
    '| Quadrant or state | Entries |', '| --- | ---: |',
    ...[...QUADRANT_STATUSES, ...(papers.some(paper => paper.quadrant === null) ? [null] : [])].map(quadrant => `| ${link(quadrant === null ? 'Not recorded' : taxonomyLabel(quadrant), browse('quadrant', quadrant))} | ${papers.filter(paper => paper.quadrant === quadrant).length} |`), '',
    '## Research topics', '',
    'These links filter the original Primary Category field. A missing original topic does not imply that the major category or quadrant is missing.', '',
    '| Research topic | Entries |', '| --- | ---: |',
    ...[...CATEGORIES, 'Uncategorized'].map(category => `| ${link(category === 'Uncategorized' ? 'Original topic not recorded' : taxonomyLabel(category), browse('category', category))} | ${papers.filter(paper => paper.primaryCategory === category).length} |`), '',
    '[← Repository overview](../README.md) · [↑ Category index](#category-index)', '',
  );
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const papers = await readJson(fileURLToPath(new URL('data/papers.json', ROOT)));
    const meta = await readJson(fileURLToPath(new URL('data/meta.json', ROOT)));
    await atomicWriteFiles([
      [fileURLToPath(new URL('README.md', ROOT)), renderReadme(papers, meta)],
      [fileURLToPath(new URL('docs/PAPERS.md', ROOT)), renderPaperCatalog(papers, meta)],
    ]);
    console.log(`Generated README.md and docs/PAPERS.md from ${papers.length} papers.`);
  } catch (error) { console.error(`README generation failed: ${error.message}`); process.exitCode = 1; }
}
